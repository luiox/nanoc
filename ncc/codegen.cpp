CodeGenerator::CodeGenerator() 
    : m_labelCounter(0), m_currentOffset(0) {
    // 初始化寄存器分配表（R0-R7）
    m_registers.resize(8, false);
}

std::string CodeGenerator::generate(Program& program) {
    m_output.clear();
    m_labelCounter = 0;
    m_currentOffset = 0;
    
    // 访问程序节点
    program.accept(*this);
    
    return m_output;
}

void CodeGenerator::emit(const std::string& code) {
    m_output += code + "\n";
}

void CodeGenerator::emitLabel(const std::string& label) {
    m_output += label + ":\n";
}

std::string CodeGenerator::newLabel() {
    return "L" + std::to_string(m_labelCounter++);
}

